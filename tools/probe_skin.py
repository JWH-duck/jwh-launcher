import sys, os
from PIL import Image

# 标准 64x64 皮肤各面 UV 区: (标签, u, v, w, h)
REGIONS = [
    ("头-前", 8, 8, 8, 8), ("头-后", 24, 8, 8, 8), ("头-右", 0, 8, 8, 8), ("头-左", 16, 8, 8, 8),
    ("头-顶", 8, 0, 8, 8), ("头-底", 16, 0, 8, 8),
    ("身-前", 20, 20, 8, 12), ("身-后", 32, 20, 8, 12), ("身-右", 16, 20, 4, 12), ("身-左", 28, 20, 4, 12),
    ("右臂-前", 44, 20, 4, 12), ("右臂-后", 52, 20, 4, 12), ("右臂-右", 40, 20, 4, 12), ("右臂-左", 48, 20, 4, 12),
    ("左臂-前", 36, 48, 4, 12), ("左臂-后", 44, 48, 4, 12), ("左臂-右", 32, 48, 4, 12), ("左臂-左", 40, 48, 4, 12),
    ("右腿-前", 4, 20, 4, 12), ("右腿-后", 12, 20, 4, 12), ("右腿-右", 0, 20, 4, 12), ("右腿-左", 8, 20, 4, 12),
    ("左腿-前", 20, 48, 4, 12), ("左腿-后", 28, 48, 4, 12), ("左腿-右", 16, 48, 4, 12), ("左腿-左", 24, 48, 4, 12),
    ("帽-前", 40, 8, 8, 8), ("帽-后", 56, 8, 8, 8), ("帽-右", 32, 8, 8, 8), ("帽-左", 48, 8, 8, 8),
    ("外套-前", 20, 36, 8, 12), ("外套-后", 32, 36, 8, 12), ("外套-右", 16, 36, 4, 12), ("外套-左", 28, 36, 4, 12),
    ("外右臂-后", 52, 36, 4, 12), ("外左臂-后", 44, 52, 4, 12),
]

def probe(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    px = im.load()
    print(f"\n=== {os.path.basename(path)}  size={w}x{h} ===")
    for label, u, v, rw, rh in REGIONS:
        if u + rw > w or v + rh > h:
            print(f"  {label:10s} 越界")
            continue
        solid = 0
        total = 0
        for y in range(v, v + rh):
            for x in range(u, u + rw):
                a = px[x, y][3]
                total += 1
                if a >= 128:
                    solid += 1
        ratio = solid / total if total else 0
        flag = "  <<< 全空" if solid == 0 else ("  半空" if ratio < 0.5 else "")
        print(f"  {label:10s} {solid:3d}/{total:3d}  {ratio*100:5.1f}%{flag}")

for p in sys.argv[1:]:
    probe(p)
